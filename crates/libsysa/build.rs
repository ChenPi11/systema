fn main() {
    prost_build::compile_protos(&["../../proto/ipc.proto"], &["../../proto/"])
        .expect("Failed to compile proto files");

    generate_paths();
}

fn generate_paths() {
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest_path = std::path::Path::new(&out_dir).join("paths.rs");

    macro_rules! path {
        ($env:literal, $default:literal) => {
            option_env!($env).unwrap_or($default)
        };
    }

    let systema_etc_dir = path!("SYSTEMA_ETC_DIR", "/etc/system-alphabet");
    let systema_run_dir = path!("SYSTEMA_RUN_DIR", "/run/system-alphabet");
    let systema_local_lib_dir = path!("SYSTEMA_LOCAL_LIB_DIR", "/usr/local/lib/system-alphabet");
    let systema_lib_dir = path!("SYSTEMA_LIB_DIR", "/usr/lib/system-alphabet");
    let systemd_etc_unit_dir = path!("SYSTEMD_ETC_UNIT_DIR", "/etc/systemd/system");
    let systemd_lib_unit_dir = path!("SYSTEMD_LIB_UNIT_DIR", "/usr/lib/systemd/system");
    let systemd_alt_unit_dir = path!("SYSTEMD_ALT_UNIT_DIR", "/lib/systemd/system");
    let systemd_generator_run_dir = path!("SYSTEMD_GENERATOR_RUN_DIR", "/run/systemd/generator");
    let systemd_generator_late_dir = path!("SYSTEMD_GENERATOR_LATE_DIR", "/run/systemd/generator.late");
    let systemd_generator_etc_dir =
        path!("SYSTEMD_GENERATOR_ETC_DIR", "/etc/systemd/system-generators");
    let systemd_generator_local_dir =
        path!("SYSTEMD_GENERATOR_LOCAL_DIR", "/usr/local/lib/systemd/system-generators");
    let systemd_generator_lib_dir =
        path!("SYSTEMD_GENERATOR_LIB_DIR", "/usr/lib/systemd/system-generators");
    let systemd_generator_alt_dir =
        path!("SYSTEMD_GENERATOR_ALT_DIR", "/lib/systemd/system-generators");
    let systemd_first_boot_file = path!("SYSTEMD_FIRST_BOOT_FILE", "/run/systemd/first-boot");
    let systemd_machine_id_file = path!("SYSTEMD_MACHINE_ID_FILE", "/etc/machine-id");
    let ipc_socket_path = path!("SYSTEMA_IPC_SOCKET", "/run/system-alphabet/allocator.sock");

    let content = format!(
        r#"// Generated by build.rs from common crate — do not edit.
// Paths can be overridden at compile time via environment variables.
// See the list of recognised variables below.

pub const SYSTEMA_ETC_DIR: &str = "{systema_etc_dir}";
pub const SYSTEMA_RUN_DIR: &str = "{systema_run_dir}";
pub const SYSTEMA_LOCAL_LIB_DIR: &str = "{systema_local_lib_dir}";
pub const SYSTEMA_LIB_DIR: &str = "{systema_lib_dir}";

pub const SYSTEMD_ETC_UNIT_DIR: &str = "{systemd_etc_unit_dir}";
pub const SYSTEMD_LIB_UNIT_DIR: &str = "{systemd_lib_unit_dir}";
pub const SYSTEMD_ALT_UNIT_DIR: &str = "{systemd_alt_unit_dir}";

pub const SYSTEMD_GENERATOR_RUN_DIR: &str = "{systemd_generator_run_dir}";
pub const SYSTEMD_GENERATOR_LATE_DIR: &str = "{systemd_generator_late_dir}";
pub const SYSTEMD_GENERATOR_ETC_DIR: &str = "{systemd_generator_etc_dir}";
pub const SYSTEMD_GENERATOR_LOCAL_DIR: &str = "{systemd_generator_local_dir}";
pub const SYSTEMD_GENERATOR_LIB_DIR: &str = "{systemd_generator_lib_dir}";
pub const SYSTEMD_GENERATOR_ALT_DIR: &str = "{systemd_generator_alt_dir}";

pub const SYSTEMD_FIRST_BOOT_FILE: &str = "{systemd_first_boot_file}";
pub const SYSTEMD_MACHINE_ID_FILE: &str = "{systemd_machine_id_file}";

pub const IPC_SOCKET_PATH: &str = "{ipc_socket_path}";

pub const UNIT_SEARCH_PATHS: &[&str] = &[
    SYSTEMA_ETC_DIR,
    SYSTEMA_RUN_DIR,
    SYSTEMA_LOCAL_LIB_DIR,
    SYSTEMA_LIB_DIR,
    SYSTEMD_ETC_UNIT_DIR,
    SYSTEMD_LIB_UNIT_DIR,
    SYSTEMD_ALT_UNIT_DIR,
];

pub const GENERATOR_SEARCH_PATHS: &[&str] = &[
    SYSTEMD_GENERATOR_RUN_DIR,
    SYSTEMD_GENERATOR_LATE_DIR,
    SYSTEMD_GENERATOR_ETC_DIR,
    SYSTEMD_GENERATOR_LOCAL_DIR,
    SYSTEMD_GENERATOR_LIB_DIR,
    SYSTEMD_GENERATOR_ALT_DIR,
];
"#,
        systema_etc_dir = systema_etc_dir,
        systema_run_dir = systema_run_dir,
        systema_local_lib_dir = systema_local_lib_dir,
        systema_lib_dir = systema_lib_dir,
        systemd_etc_unit_dir = systemd_etc_unit_dir,
        systemd_lib_unit_dir = systemd_lib_unit_dir,
        systemd_alt_unit_dir = systemd_alt_unit_dir,
        systemd_generator_run_dir = systemd_generator_run_dir,
        systemd_generator_late_dir = systemd_generator_late_dir,
        systemd_generator_etc_dir = systemd_generator_etc_dir,
        systemd_generator_local_dir = systemd_generator_local_dir,
        systemd_generator_lib_dir = systemd_generator_lib_dir,
        systemd_generator_alt_dir = systemd_generator_alt_dir,
        systemd_first_boot_file = systemd_first_boot_file,
        systemd_machine_id_file = systemd_machine_id_file,
        ipc_socket_path = ipc_socket_path,
    );

    std::fs::write(&dest_path, content).unwrap();

    println!("cargo:rerun-if-env-changed=SYSTEMA_ETC_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMA_RUN_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMA_LOCAL_LIB_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMA_LIB_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_ETC_UNIT_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_LIB_UNIT_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_ALT_UNIT_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_RUN_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_LATE_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_ETC_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_LOCAL_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_LIB_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_GENERATOR_ALT_DIR");
    println!("cargo:rerun-if-env-changed=SYSTEMD_FIRST_BOOT_FILE");
    println!("cargo:rerun-if-env-changed=SYSTEMD_MACHINE_ID_FILE");
    println!("cargo:rerun-if-env-changed=SYSTEMA_IPC_SOCKET");
}